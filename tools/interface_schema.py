"""Emit the browser's runtime wire schema from the authoritative Python DTOs."""
import json
from pathlib import Path
import types
from typing import Literal, Union, get_args, get_origin, get_type_hints, is_typeddict

from tsp_hpc.interface import contracts


def schema():
    definitions = {}

    def describe(kind):
        if is_typeddict(kind):
            name = kind.__name__
            if name not in definitions:
                definitions[name] = {}
                definitions[name] = {key: describe(value) for key, value in get_type_hints(kind).items()}
            return {"ref": name}
        origin, args = get_origin(kind), get_args(kind)
        if origin is Literal:
            return {"literal": list(args)}
        if origin in (Union, types.UnionType):
            return {"union": [describe(arg) for arg in args]}
        if origin is list:
            return {"list": describe(args[0])}
        if origin is dict:
            return {"map": describe(args[1])}
        return {str: "string", int: "integer", float: "number", bool: "boolean", type(None): "null", object: "json"}[kind]

    for kind in vars(contracts).values():
        if is_typeddict(kind):
            describe(kind)
    return definitions


def serialized():
    return json.dumps(schema(), sort_keys=True, separators=(",", ":")) + "\n"


def typescript():
    """Static response types and runtime shapes share the same authority."""
    def describe(value):
        if isinstance(value, str):
            return {"integer": "number", "json": "JsonValue"}.get(value, value)
        if "ref" in value:
            return f'WireTypes[{json.dumps(value["ref"])}]'
        if "literal" in value:
            return " | ".join(json.dumps(item) for item in value["literal"])
        if "union" in value:
            return " | ".join(describe(item) for item in value["union"])
        if "list" in value:
            return f'Array<{describe(value["list"])}>'
        return f'Record<string, {describe(value["map"])}>'

    lines = ["// Generated by tools/interface_schema.py; do not edit.",
             "import type { JsonValue } from './contracts';", "export interface WireTypes {"]
    for name, fields in sorted(schema().items()):
        lines.append(f'  {name}: {{')
        for key, value in sorted(fields.items()):
            lines.append(f'    {key}: {describe(value)};')
        lines.append('  };')
    aliases = [f"export type {name} = WireTypes['{name}'];" for name in sorted(schema())]
    return "\n".join([*lines, "}", *aliases, ""])


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "frontend/src"
    (target / "wire-schema.json").write_text(serialized())
    (target / "wire-types.ts").write_text(typescript())
